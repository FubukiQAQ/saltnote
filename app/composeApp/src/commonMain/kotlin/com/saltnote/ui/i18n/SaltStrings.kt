enum class AppLanguage(val code: String, val nativeLabel: String) {
    System("system", "System"),
    ZhCn("zh-CN", "简体中文"),
    ZhTw("zh-TW", "繁體中文"),
    En("en", "English"),
    Ja("ja", "日本語"),
    Ko("ko", "한국어"),
}

enum class AiOutputLanguage(val code: String) {
    FollowUi("follow_ui"),
    ZhCn("zh-CN"),
    ZhTw("zh-TW"),
    En("en"),
    Ja("ja"),
    Ko("ko"),
}

fun resolveAppLanguage(uiPrefCode: String, systemTag: String): AppLanguage {
    val pref = uiPrefCode.trim().lowercase()
    when (pref) {
        "zh-cn", "zh_cn", "zh-hans" -> return AppLanguage.ZhCn
        "zh-tw", "zh_tw", "zh-hk", "zh-mo", "zh-hant" -> return AppLanguage.ZhTw
        "en", "en-us", "en-gb" -> return AppLanguage.En
        "ja", "ja-jp" -> return AppLanguage.Ja
        "ko", "ko-kr" -> return AppLanguage.Ko
    }
    val sys = systemTag.trim().lowercase()
    return when {
        sys.contains("hant") || sys.startsWith("zh-tw") || sys.startsWith("zh-hk") || sys.startsWith("zh-mo") -> AppLanguage.ZhTw
        sys.startsWith("zh") -> AppLanguage.ZhCn
        sys.startsWith("ja") -> AppLanguage.Ja
        sys.startsWith("ko") -> AppLanguage.Ko
        else -> AppLanguage.En
    }
}

fun resolveAiOutputLanguageCode(aiPrefCode: String, uiPrefCode: String, systemTag: String): String {
    val pref = aiPrefCode.trim().lowercase()
    return when (pref) {
        "zh-cn", "zh_cn", "zh-hans" -> "zh-CN"
        "zh-tw", "zh_tw", "zh-hk", "zh-mo", "zh-hant" -> "zh-TW"
        "en", "en-us", "en-gb" -> "en"
        "ja", "ja-jp" -> "ja"
        "ko", "ko-kr" -> "ko"
        else -> when (resolveAppLanguage(uiPrefCode, systemTag)) {
            AppLanguage.ZhCn -> "zh-CN"
            AppLanguage.ZhTw -> "zh-TW"
            AppLanguage.En -> "en"
            AppLanguage.Ja -> "ja"
            AppLanguage.Ko -> "ko"
            AppLanguage.System -> "en"
        }
    }
}

